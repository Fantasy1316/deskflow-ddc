pub fn identity(dir: &Path) -> Result<String> {
    let path = dir.join("identity.pem");
    if !path.exists() {
        let pair = rcgen::generate_simple_self_signed(vec!["deskflow-ddc.local".into()])?;
        atomic_write(
            &path,
            format!("{}\n{}", pair.key_pair.serialize_pem(), pair.cert.pem()).as_bytes(),
        )?;
    }
    let text = std::fs::read_to_string(path)?;
    rcgen::KeyPair::from_pem(&text).context("引擎私钥损坏")?;
    // Extract the DER without depending on certificate subject or key algorithm.
    use base64::Engine;
    let cert = text
        .split("-----BEGIN CERTIFICATE-----")
        .nth(1)
        .context("缺少引擎证书")?
        .split("-----END CERTIFICATE-----")
        .next()
        .unwrap();
    rcgen::CertificateParams::from_ca_cert_pem(&format!(
        "-----BEGIN CERTIFICATE-----{cert}-----END CERTIFICATE-----"
    ))
    .context("引擎证书损坏")?;
    let der = base64::engine::general_purpose::STANDARD.decode(
        cert.chars()
            .filter(|c| !c.is_whitespace())
            .collect::<String>(),
    )?;
    Ok(hex::encode(Sha256::digest(der)))
}
fn ini(path: &str) -> String {
    format!("\"{}\"", path.replace('\\', "/").replace('"', "\\\""))
}
pub fn server_config(c: &Config, local: &str, peer: &str, peer_retained: bool) -> Result<String> {
    c.validate()?;
    uuid::Uuid::parse_str(local)?;
    uuid::Uuid::parse_str(peer)?;
    let (host, client) = if c.role == "host" {
        (local, peer)
    } else {
        (peer, local)
    };
    // With neither computer having a separate visible screen, no edge can
    // transfer input safely in manual-video mode. Explicit hotkeys still work.
    let side =
        if c.cross_screen_video == "manual" && c.retained_display_id.is_empty() && !peer_retained {
            "off"
        } else {
            c.layout_side.as_str()
        };
    let edges = match side {
        "left" => Some(("right", "left")),
        "right" => Some(("left", "right")),
        "top" => Some(("down", "up")),
        "bottom" => Some(("up", "down")),
        _ => None,
    };
    let mut text = format!("# Generated by Deskflow DDC.\nsection: links\n\tsb-{host}:");
    if let Some((out, _)) = edges {
        text += &format!("\n\t\t{out} = sb-{client}");
    }
    text += &format!("\n\tsb-{client}:");
    if let Some((_, back)) = edges {
        text += &format!("\n\t\t{back} = sb-{host}");
    }
    text += "\nend\nsection: options\n";
    let chord = |s: &str| {
        if crate::model::platform() == "darwin" {
            s.replace("alt", "super")
        } else {
            s.into()
        }
    };
    if c.cross_screen_video != "manual" && (edges.is_none() || c.cross_screen_video != "keep") {
        text += &format!("\tkeystroke({}) = switchToNextScreen\n", chord(&c.shortcut));
    }
    for (key, target) in [
        ("control+alt+Escape", host),
        ("control+alt+shift+F18", host),
        ("control+alt+shift+F19", client),
    ] {
        text += &format!(
            "\tkeystroke({}) = switchToScreen(sb-{target})\n",
            chord(key)
        );
    }
    text += "end\n";
    Ok(text)
}
pub fn prepare(
    c: &Config,
    local: &str,
    peer: &Identity,
    dir: &Path,
    address: &str,
) -> Result<PathBuf> {
    c.ready()?;
    peer.validate()?;
    let root = dir.join("deskflow");
    let tls = root.join("tls");
    std::fs::create_dir_all(&tls)?;
    atomic_write(
        &tls.join("identity.pem"),
        &std::fs::read(dir.join("identity.pem"))?,
    )?;
    atomic_write(
        &tls.join(if c.role == "host" {
            "trusted-clients"
        } else {
            "trusted-servers"
        }),
        format!("v2:sha256:{}\n", peer.fingerprint).as_bytes(),
    )?;
    atomic_write(
        &root.join("server.conf"),
        server_config(c, local, &peer.id.to_string(), peer.retained_display)?.as_bytes(),
    )?;
    let (host, client) = if c.role == "host" {
        (local.to_string(), peer.id.to_string())
    } else {
        (peer.id.to_string(), local.to_string())
    };
    let text=format!("[core]\ncomputerName=sb-{local}\ncoreMode={}\nprocessMode=0\nport={}\ninterface=\npreventSleep=false\n\n[security]\ntlsEnabled=true\ncheckPeerFingerprints=true\ncertificate={}\n\n[client]\nremoteHost={}\n\n[server]\nexternalConfig=true\nexternalConfigFile={}\nenableClipboard={}\nclipboardSize={}\n\n[log]\nlevel=INFO\ntoFile=false\n\n[computer_sb-{host}]\nname=sb-{host}\n\n[computer_sb-{client}]\nname=sb-{client}\n",if c.role=="host"{2}else{1},c.deskflow_port,ini(&tls.join("identity.pem").to_string_lossy()),ini(address),ini(&root.join("server.conf").to_string_lossy()),c.clipboard,c.clipboard_megabytes);
    let settings = root.join("Deskflow.conf");
    atomic_write(&settings, text.as_bytes())?;
    Ok(settings)
}
pub fn namespace(dir: &Path) -> PathBuf {
    std::env::temp_dir().join(format!(
        "ddc-core-{}",
        &hex::encode(Sha256::digest(dir.to_string_lossy().as_bytes()))[..16]
    ))
}
#[cfg(unix)]
async fn connect_ipc(path: &Path) -> Result<tokio::net::UnixStream> {
    Ok(tokio::net::UnixStream::connect(path).await?)
}
#[cfg(windows)]
async fn connect_ipc(_path: &Path) -> Result<tokio::net::windows::named_pipe::NamedPipeClient> {
    Ok(tokio::net::windows::named_pipe::ClientOptions::new().open(r"\\.\pipe\deskflow-core")?)
}
async fn preflight(path: &Path) -> Result<()> {
    match tokio::time::timeout(Duration::from_secs(1), connect_ipc(path)).await {
        Ok(Ok(_)) => bail!("检测到仍在运行的 Deskflow 引擎，已阻止开始共享。删除旧应用不会结束其进程；请先退出旧版和独立 Deskflow，无法退出时请重启电脑。未接管该引擎"),
        Ok(Err(e)) => {
            let harmless = e.downcast_ref::<std::io::Error>().is_some_and(|e| {
                matches!(
                    e.kind(),
                    std::io::ErrorKind::NotFound | std::io::ErrorKind::ConnectionRefused
                )
            });
            ensure!(harmless, "无法检查已有引擎：{e}");
        }
        Err(_) => bail!("检查已有引擎超时"),
    }
    Ok(())
}
// This only opens known IPC endpoints to check ownership; it never sends a
// control command or terminates a process started by another application.
pub async fn assert_no_running_engine(dir: &Path) -> Result<()> {
    let root = std::env::temp_dir();
    let mut paths = vec![root.join("deskflow-core")];
    #[cfg(target_os = "macos")]
    {
        paths.push(namespace(dir).join("deskflow-core"));
        // Deleted/replaced .app bundles can leave an engine in the data tree.
        // Check both Electron and Tauri namespaces before starting any session.
        for entry in std::fs::read_dir(&root)? {
            let entry = entry?;
            let name = entry.file_name();
            let name = name.to_string_lossy();
            if entry.file_type()?.is_dir()
                && (name.starts_with("sb-core-") || name.starts_with("ddc-core-"))
            {
                paths.push(entry.path().join("deskflow-core"));
            }
        }
    }
    #[cfg(not(target_os = "macos"))]
    let _ = dir;
    paths.sort();
    paths.dedup();
    for path in paths {
        preflight(&path).await?;
    }
    Ok(())
}
pub struct Engine {
    pid: u32,
    stop: mpsc::Sender<oneshot::Sender<Result<()>>>,
    task: tokio::task::JoinHandle<()>,
}
impl Engine {
    pub async fn start(
        binary: PathBuf,
        c: &Config,
        settings: &Path,
        dir: &Path,
        events: mpsc::Sender<Event>,
    ) -> Result<Self> {
        let temp = namespace(dir);
        std::fs::create_dir_all(&temp)?;
        assert_no_running_engine(dir).await?;
        let ipc = if cfg!(target_os = "macos") {
            temp.join("deskflow-core")
        } else {
            std::env::temp_dir().join("deskflow-core")
        };
        if c.role == "host" {
            drop(
                tokio::net::TcpListener::bind(("0.0.0.0", c.deskflow_port))
                    .await
                    .context("键鼠端口已被占用")?,
            );
        }
        let mut command = Command::new(binary);
        command
            .arg(if c.role == "host" { "server" } else { "client" })
            .args(["--settings"])
            .arg(settings)
            .stdin(Stdio::null())
            .stdout(Stdio::piped())
            .stderr(Stdio::piped())
            .kill_on_drop(true);
        if cfg!(target_os = "macos") {
            command.env("TMPDIR", format!("{}/", temp.display()));
        }
        command
            .env("XDG_CONFIG_HOME", dir.join("isolated-config"))
            .env("XDG_STATE_HOME", dir.join("isolated-state"));
        #[cfg(windows)]
        command.creation_flags(0x08000000);
        let mut child = command.spawn().context("无法启动内置键鼠引擎")?;
        let pid = child.id().context("无法获取键鼠引擎进程 ID")?;
        for pipe in [
            child
                .stdout
                .take()
                .map(|s| Box::new(s) as Box<dyn tokio::io::AsyncRead + Unpin + Send>),
            child
                .stderr
                .take()
                .map(|s| Box::new(s) as Box<dyn tokio::io::AsyncRead + Unpin + Send>),
        ]
        .into_iter()
        .flatten()
        {
            let tx = events.clone();
            tokio::spawn(async move {
                let mut framed = tokio_util::codec::FramedRead::new(
                    pipe,
                    tokio_util::codec::LinesCodec::new_with_max_length(16384),
                );
                use futures_util::StreamExt;
                while let Some(Ok(line)) = framed.next().await {
                    if !line.contains("DEBUG")
                        && !line.contains("VERBOSE")
                        && !line.to_lowercase().contains("clipboard")
                    {
                        if tx.send(Event::Output(line)).await.is_err() {
                            break;
                        }
                    }
                }
            });
        }
        let (ipc_stop, mut ipc_rx) = mpsc::channel::<()>(1);
        let tx = events.clone();
        let ipc_task = tokio::spawn(async move {
            for _ in 0..72 {
                match connect_ipc(&ipc).await {
                    Ok(socket) => {
                        use futures_util::StreamExt;
                        let (read, mut write) = tokio::io::split(socket);
                        let mut lines = tokio_util::codec::FramedRead::new(
                            read,
                            tokio_util::codec::LinesCodec::new_with_max_length(65536),
                        );
                        let mut ready = false;
                        if write
                            .write_all(b"hello=screenbridge-probe\n")
                            .await
                            .is_err()
                        {
                            break;
                        }
                        loop {
                            tokio::select! {
                                line = lines.next() => {
                                    let Some(Ok(line)) = line else { break };
                                    if let Some(version)=line.strip_prefix("versionMismatch=") {
                                        if version.len()>256 || version.contains(['\r','\n']) { break; }
                                        if write.write_all(format!("hello={version}\n").as_bytes()).await.is_err() { break; }
                                    }
                                    if line.starts_with("hello=") { ready=true; }
                                    if tx.send(Event::Ipc(line)).await.is_err() { return; }
                                },
                                stop = ipc_rx.recv() => {
                                    if stop.is_some() && ready { let _=write.write_all(b"stop\n").await; }
                                    return;
                                }
                            }
                        }
                    }
                    Err(_) => tokio::time::sleep(Duration::from_millis(250)).await,
                }
            }
            let _ = tx.send(Event::Ipc("observerDisconnected".into())).await;
        });
        let (stop, mut rx) = mpsc::channel::<oneshot::Sender<Result<()>>>(1);
        let task = tokio::spawn(async move {
            let reason = tokio::select! {
             result=child.wait()=>format!("{result:?}"),
             request=rx.recv()=>{
              let _=ipc_stop.send(()).await;
              let result=stop_child(&mut child).await;
              let reason=if result.is_ok(){"stopped".to_string()}else{format!("{result:?}")};
              if let Some(reply)=request{let _=reply.send(result);}
              reason
             }
            };
            ipc_task.abort();
            let _ = events.send(Event::Exited(reason)).await;
        });
        Ok(Self { pid, stop, task })
    }
    pub fn pid(&self) -> u32 {
        self.pid
    }
    pub async fn stop(&mut self) -> Result<()> {
        if self.task.is_finished() {
            return Ok(());
        }
        let (tx, rx) = oneshot::channel();
        if self.stop.send(tx).await.is_err() {
            (&mut self.task).await?;
            return Ok(());
        }
        rx.await.context("等待键鼠引擎退出失败")??;
        Ok(())
    }
}
async fn stop_child(child: &mut Child) -> Result<()> {
    if let Ok(result) = tokio::time::timeout(Duration::from_millis(1500), child.wait()).await {
        result.context("等待引擎退出失败")?;
        return Ok(());
    }
    #[cfg(unix)]
    if let Some(pid) = child.id() {
        unsafe {
            libc::kill(pid as i32, libc::SIGTERM);
        }
    }
    #[cfg(windows)]
    child.start_kill()?;
    if let Ok(result) = tokio::time::timeout(Duration::from_millis(1500), child.wait()).await {
        result.context("等待引擎退出失败")?;
        return Ok(());
    }
    child.kill().await.context("引擎仍未退出，禁止重复启动")?;
    child.wait().await?;
    Ok(())
}
#[cfg(test)]
mod tests {
    use super::*;
    #[test]
    fn stable_namespace_and_distinct_profile() {
        assert_eq!(namespace(Path::new("/a")), namespace(Path::new("/a")));
        assert_ne!(namespace(Path::new("/a")), namespace(Path::new("/b")));
    }
    #[test]
    fn rejects_certificate_and_config_injection() {
        let c = Config {
            shortcut: "bad\nend".into(),
            ..Config::default()
        };
        assert!(server_config(
            &c,
            &uuid::Uuid::new_v4().to_string(),
            &uuid::Uuid::new_v4().to_string(),
            false,
        )
        .is_err());
    }
    #[test]
    fn cert_persists_and_fingerprint_is_stable() {
        let dir = tempfile::tempdir().unwrap();
        assert_eq!(identity(dir.path()).unwrap(), identity(dir.path()).unwrap());
    }
    #[test]
    fn manual_mode_disables_invisible_edges_and_does_not_bind_the_video_shortcut() {
        let host = uuid::Uuid::new_v4().to_string();
        let peer = uuid::Uuid::new_v4().to_string();
        for side in ["left", "right", "top", "bottom"] {
            let mut c = Config {
                layout_side: side.into(),
                ..Config::default()
            };
            let config = server_config(&c, &host, &peer, false).unwrap();
            assert!(!config.contains(" = sb-"));
            assert!(!config.contains("switchToNextScreen"));
            assert!(config.contains("switchToScreen"));
            c.retained_display_id = "internal".into();
            let config = server_config(&c, &host, &peer, false).unwrap();
            assert!(config.contains(" = sb-"));
            assert!(!config.contains("switchToNextScreen"));
        }
        let c = Config {
            layout_side: "left".into(),
            ..Config::default()
        };
        assert!(server_config(&c, &host, &peer, true)
            .unwrap()
            .contains(" = sb-"));
    }
}

#[cfg(all(test, unix))]
mod process_tests {
    use super::*;
    #[tokio::test]
    async fn existing_engine_preflight_never_sends_control_commands() {
        use tokio::io::AsyncReadExt;
        let dir = tempfile::tempdir().unwrap();
        let path = dir.path().join("deskflow-core");
        let server = tokio::net::UnixListener::bind(&path).unwrap();
        let error = preflight(&path).await.unwrap_err().to_string();
        assert!(error.contains("阻止开始共享"));
        let (mut socket, _) = server.accept().await.unwrap();
        let mut received = [0; 32];
        assert_eq!(socket.read(&mut received).await.unwrap(), 0);
        drop(server);
        // A stale socket file is not evidence that an engine is alive.
        assert!(preflight(&path).await.is_ok());
    }
    #[tokio::test]
    async fn escalates_only_owned_child_and_reaps_it() {
        use tokio::io::{AsyncBufReadExt, BufReader};
        let mut child=Command::new("python3").args(["-c","import signal,time; signal.signal(signal.SIGTERM,signal.SIG_IGN); print('ready',flush=True); time.sleep(60)"]).stdout(Stdio::piped()).kill_on_drop(true).spawn().unwrap();
        let mut output = BufReader::new(child.stdout.take().unwrap());
        let mut line = String::new();
        output.read_line(&mut line).await.unwrap();
        assert_eq!(line.trim(), "ready");
        tokio::time::timeout(Duration::from_secs(5), stop_child(&mut child))
            .await
            .unwrap()
            .unwrap();
        assert!(child.id().is_none());
        assert!(child.try_wait().unwrap().is_some());
    }
}
