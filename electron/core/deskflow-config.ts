import type { Config } from '../../src/shared/types.js'
export const HOST_CHORD = 'control+alt+shift+F18'
export const PEER_CHORD = 'control+alt+shift+F19'
export const RECOVERY_CHORD = 'control+alt+Escape'
export function screenName(id: string) {
  if (!/^[a-f0-9-]{36}$/.test(id)) throw new Error('设备身份格式无效')
  return `sb-${id}`
}
function ini(v: string) {
  return '"' + v.replace(/\\/g, '/').replace(/"/g, '\\"') + '"'
}
export function makeServerConfig(
  hostId: string,
  clientId: string,
  shortcut: string,
  platform = process.platform,
  layoutSide: Config['layoutSide'] = 'off',
  video: Config['crossScreenVideo'] = 'follow',
) {
  if (!/^control\+alt\+(shift\+)?F(?:[1-9]|1[0-7])$/.test(shortcut))
    throw new Error('快捷键格式无效')
  const host = screenName(hostId),
    client = screenName(clientId)
  // Deskflow 1.27 OSXKeyState::mapDeskflowHotKeyToMac registers Alt as Command,
  // and Super as Option. Keep the app's Ctrl+Option contract on a Mac host.
  const key = (chord: string) =>
    platform === 'darwin' ? chord.replace(/\balt\b/g, 'super') : chord
  if (!['off', 'left', 'right', 'top', 'bottom'].includes(layoutSide))
    throw new Error('电脑相对位置无效')
  // Native links work in either direction on every supported platform.
  // PointerBridge also handles a selected visible panel inside a larger desktop.
  const pointer = layoutSide !== 'off'
  const directions = {
    left: ['left', 'right'],
    right: ['right', 'left'],
    top: ['up', 'down'],
    bottom: ['down', 'up'],
  } as const
  const edges = pointer ? directions[layoutSide as Exclude<Config['layoutSide'], 'off'>] : null
  const hostLink = edges ? `\n\t\t${edges[1]} = ${client}` : ''
  const clientLink = edges ? `\n\t\t${edges[0]} = ${host}` : ''
  const shortcutRule =
    pointer && video === 'keep' ? '' : `\tkeystroke(${key(shortcut)}) = switchToNextScreen\n`
  // Deskflow 1.27's argument parser rejects empty parentheses. Omit them for zero-argument actions.
  return `# Generated by Deskflow DDC.\nsection: links\n\t${host}:${hostLink}\n\t${client}:${clientLink}\nend\nsection: options\n${shortcutRule}\tkeystroke(${key(RECOVERY_CHORD)}) = switchToScreen(${host})\n\tkeystroke(${key(HOST_CHORD)}) = switchToScreen(${host})\n\tkeystroke(${key(PEER_CHORD)}) = switchToScreen(${client})\nend\n`
}
export function makeSettings(
  c: Config,
  localId: string,
  peerId: string,
  root: string,
  fingerprint: string,
  serverAddress: string,
) {
  if (!/^[a-f0-9]{64}$/.test(fingerprint)) throw new Error('对端证书指纹无效')
  const hostId = c.role === 'host' ? localId : peerId
  const clientId = c.role === 'client' ? localId : peerId
  const text = `[core]\ncomputerName=${screenName(localId)}\ncoreMode=${c.role === 'host' ? 2 : 1}\nprocessMode=0\nport=${c.deskflowPort}\ninterface=\npreventSleep=false\n\n[security]\ntlsEnabled=true\ncheckPeerFingerprints=true\ncertificate=${ini(root + '/tls/identity.pem')}\n\n[client]\nremoteHost=${ini(serverAddress)}\n\n[server]\nexternalConfig=true\nexternalConfigFile=${ini(root + '/server.conf')}\nenableClipboard=${c.clipboard}\nclipboardSize=${c.clipboardMegabytes}\n\n[log]\nlevel=INFO\ntoFile=false\n\n[computer_${screenName(hostId)}]\nname=${screenName(hostId)}\n\n[computer_${screenName(clientId)}]\nname=${screenName(clientId)}\n`
  return { text, trust: `v2:sha256:${fingerprint}\n` }
}
export function parseSwitch(line: string): { from: string; to: string } | null {
  const match = line.match(/switch from "(sb-([a-f0-9-]{36}))" to "(sb-([a-f0-9-]{36}))"/)
  return match ? { from: match[2]!, to: match[4]! } : null
}
